import pandas as pd
from transformers import pipeline

data = pd.read_csv("ronaldo_text_clean.csv")

model = pipeline(
    "text-classification",
    model="cardiffnlp/twitter-roberta-base-sentiment-latest"
)

hasil = model(
    data["text_clean"].fillna("").astype(str).tolist(),
    batch_size=16,
    truncation=True,
    max_length=512
)

data["sentimen"] = [
    item["label"].capitalize() for item in hasil
]

data["confidence"] = [
    item["score"] for item in hasil
]

data.to_csv("ronaldo_labeled.csv", index=False)